/// Keeps what you copy (docs/design.md, "Clipboard"), in the App Group so the app shows the history the keyboard keeps,
/// never online. Nothing runs in the background: the keyboard looks at the clipboard when it appears and when the
/// clipboard panel opens, and the app when it comes to the front, and each keeps whatever changed since either last
/// looked. Reading the clipboard needs Full Access, and Paste from Other Apps (`refused`).
///
/// The history grows for as long as you keep it, so every read and write of its files happens on a queue of its own,
/// never on the main thread where keys are typed; `history` is what the queue last read, and `onChange` says when
/// that changed.
public final class ClipboardStore {
    nonisolated fileprivate struct Saved: Codable, Sendable {
        var history = ClipboardHistory()
        var seen = 0
        /// Whether iOS refused the last look at the clipboard.
        var refused: Bool?
    }

    private let disk: Disk
    private let queue = DispatchQueue(label: "com.shahidy.hexkeyboard.clipboard", qos: .userInitiated)
    private var saved: Saved?
    /// The history or `refused` changed, on the main thread.
    public var onChange: () -> Void = {}

    /// Password managers mark what they copy with these, so it's never kept.
    nonisolated static let concealed = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    public static let shared = FileManager.default.containerURL(forSecurityApplicationGroupIdentifier: SettingsStore.appGroup)?.appending(path: "Library/clipboard")
    static let own = URL.applicationSupportDirectory.appending(path: "clipboard")

    /// `backup` is the keyboard's own copy of everything, since iOS deletes the group's container whenever an install
    /// leaves no app claiming the group: a group without a history takes this one. The history the keyboard kept
    /// before the group held it joins the group's once (`Disk.moved`), whatever the group had by then, with any image
    /// file whose row was lost.
    public init(folder: URL? = ClipboardStore.shared, backup: URL? = nil) {
        let folder = folder ?? Self.own
        disk = Disk(folder: folder, backup: backup == folder ? nil : backup)
    }

    public var history: ClipboardHistory { saved?.history ?? ClipboardHistory() }

    /// Whether the history has been read yet, so a panel shows nothing rather than an empty history meanwhile.
    public var loaded: Bool { saved != nil }

    /// Whether the history is in the folder yet. The keyboard starts it, from its own copy when it has one, so the app
    /// keeps nothing before then: what it kept would stand in for everything the keyboard had.
    public var started: Bool { disk.started }

    /// Whether iOS refused the keyboard's last look at the clipboard. iOS counts a keyboard's reads as its app's, even
    /// inside another app, and without asking refuses them unless Settings › Apps › Hex › Paste from Other Apps is Allow.
    public var refused: Bool { saved?.refused == true }

    /// Keeps what's on the clipboard if it changed since the keyboard last looked.
    public func catchUp(_ pasteboard: UIPasteboard = .general, now: Date = .now) {
        let time = now.timeIntervalSince1970
        update { saved, disk in disk.keep(pasteboard, at: time, in: &saved) }
    }

    /// Something the keyboard put on the clipboard itself, which it doesn't keep.
    public func skip(changeCount: Int) {
        update { saved, _ in
            saved.seen = changeCount
            return true
        }
    }

    public func setPinned(_ pinned: Bool, _ content: ClipboardHistory.Item.Content) {
        saved?.history.setPinned(pinned, content)
        update { saved, _ in
            saved.history.setPinned(pinned, content)
            return true
        }
    }

    public func remove(_ content: ClipboardHistory.Item.Content) {
        saved?.history.remove(content)
        update { saved, disk in
            saved.history.remove(content)
            disk.delete([content])
            return true
        }
    }

    /// Deletes everything but what's pinned.
    public func removeUnpinned() {
        _ = saved?.history.removeUnpinned()
        update { saved, disk in
            disk.delete(saved.history.removeUnpinned())
            return true
        }
    }

    /// Puts an image item back on the clipboard, for you to paste.
    public func copy(image name: String, to pasteboard: UIPasteboard = .general) {
        update { saved, disk in
            guard let data = try? Data(contentsOf: disk.folder.appending(path: name)), let type = UTType(filenameExtension: (name as NSString).pathExtension) else { return false }
            pasteboard.setData(data, forPasteboardType: type.identifier)
            saved.seen = pasteboard.changeCount
            return true
        }
    }

    /// A small image for an image item's row, decoded at the size it shows, so a big screenshot never fills the
    /// keyboard's memory. It reads the file, so call it off the main thread.
    nonisolated public func thumbnail(_ name: String, side: CGFloat) -> UIImage? {
        Self.thumbnail(of: file(name), side: side)
    }

    /// An image item's file.
    nonisolated public func file(_ name: String) -> URL { disk.folder.appending(path: name) }

    nonisolated public static func thumbnail(of file: URL, side: CGFloat) -> UIImage? {
        guard let source = CGImageSourceCreateWithURL(file as CFURL, nil),
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: side, kCGImageSourceCreateThumbnailWithTransform: true] as CFDictionary)
        else { return nil }
        return UIImage(cgImage: image)
    }

    /// Reads the history again, for what another process kept.
    public func reload() {
        update { _, _ in false }
    }

    /// Returns once everything asked of the store so far is done and `history` shows it.
    public func settled() async {
        await withCheckedContinuation { done in
            queue.async { DispatchQueue.main.async { done.resume() } }
        }
    }

    /// iOS can run the keyboard in more than one app at once, and the app beside it, so each change reads the file
    /// first, and one never writes over what another kept. `edit` says whether it changed anything to write.
    private func update(_ edit: @escaping @Sendable (inout Saved, Disk) -> Bool) {
        let mine = saved
        queue.async { [disk] in
            var latest = disk.load() ?? mine ?? Saved()
            if edit(&latest, disk) { disk.save(latest) }
            DispatchQueue.main.async {
                MainActor.assumeIsolated { [weak self] in
                    guard let self else { return }
                    saved = latest
                    onChange()
                }
            }
        }
    }
}

/// The history's files: `history.json` and an image file per image item, in the folder, with the same in the backup.
nonisolated private struct Disk: Sendable {
    let folder: URL
    let backup: URL?

    static let moved = "moved"

    var started: Bool { FileManager.default.fileExists(atPath: folder.appending(path: "history.json").path(percentEncoded: false)) }

    /// The history as the folder holds it, or the backup's when the folder lost it, with the backup's own history
    /// joined in once.
    func load() -> ClipboardStore.Saved? {
        guard var saved = Self.read(folder) ?? restore() else { return nil }
        guard let backup, !FileManager.default.fileExists(atPath: backup.appending(path: Self.moved).path(percentEncoded: false)), let kept = Self.read(backup) else { return saved }
        let files = (try? FileManager.default.contentsOfDirectory(atPath: backup.path(percentEncoded: false))) ?? []
        for name in files where name != "history.json" {
            try? FileManager.default.copyItem(at: backup.appending(path: name), to: folder.appending(path: name))
        }
        saved.history.add(kept.history.items)
        saved.history.add(files.filter { UTType(filenameExtension: ($0 as NSString).pathExtension)?.conforms(to: .image) == true }.map { name in
            let found = (try? FileManager.default.attributesOfItem(atPath: backup.appending(path: name).path(percentEncoded: false))[.modificationDate] as? Date) ?? .now
            return ClipboardHistory.Item(content: .image(name), found: found.timeIntervalSince1970)
        })
        if save(saved) { FileManager.default.createFile(atPath: backup.appending(path: Self.moved).path(percentEncoded: false), contents: nil) }
        return saved
    }

    /// Keeps what's on the clipboard if it changed since `saved` last looked, and says whether `saved` changed.
    func keep(_ pasteboard: UIPasteboard, at time: Double, in saved: inout ClipboardStore.Saved) -> Bool {
        guard pasteboard.changeCount != saved.seen else { return false }
        guard !pasteboard.types.contains(where: ClipboardStore.concealed.contains) else {
            saved.seen = pasteboard.changeCount
            return true
        }
        let content: ClipboardHistory.Item.Content?
        if pasteboard.hasStrings {
            content = pasteboard.string.map(ClipboardHistory.Item.Content.text)
        } else if pasteboard.hasImages {
            content = Self.imageData(pasteboard).map(saveImage)
        } else {
            saved.seen = pasteboard.changeCount
            return true
        }
        let refused = content == nil
        let changed = saved.refused != refused
        saved.refused = refused
        guard let content else { return changed }
        saved.seen = pasteboard.changeCount
        if case .text(let text) = content, text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return true }
        saved.history.keep(content, at: time)
        return true
    }

    func delete(_ contents: [ClipboardHistory.Item.Content]) {
        for case .image(let name) in contents { try? FileManager.default.removeItem(at: folder.appending(path: name)) }
    }

    /// Whether the group took it: the keyboard can write there only with Full Access.
    @discardableResult func save(_ saved: ClipboardStore.Saved) -> Bool {
        let kept = Self.write(saved, to: folder)
        guard let backup else { return kept }
        Self.write(saved, to: backup)
        let images = Set(saved.history.items.compactMap { if case .image(let name) = $0.content { name } else { nil } })
        let backedUp = Set((try? FileManager.default.contentsOfDirectory(atPath: backup.path(percentEncoded: false))) ?? []).subtracting(["history.json", Self.moved])
        for name in images.subtracting(backedUp) { try? FileManager.default.copyItem(at: folder.appending(path: name), to: backup.appending(path: name)) }
        for name in backedUp.subtracting(images) { try? FileManager.default.removeItem(at: backup.appending(path: name)) }
        return kept
    }

    private func restore() -> ClipboardStore.Saved? {
        guard let backup, let saved = Self.read(backup) else { return nil }
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        for name in (try? FileManager.default.contentsOfDirectory(atPath: backup.path(percentEncoded: false))) ?? [] {
            try? FileManager.default.copyItem(at: backup.appending(path: name), to: folder.appending(path: name))
        }
        return saved
    }

    private func saveImage(_ image: (data: Data, type: UTType)) -> ClipboardHistory.Item.Content {
        let name = SHA256.hash(data: image.data).map { String(format: "%02x", $0) }.joined() + "." + (image.type.preferredFilenameExtension ?? "img")
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try? image.data.write(to: folder.appending(path: name), options: .atomic)
        return .image(name)
    }

    private static func read(_ folder: URL) -> ClipboardStore.Saved? {
        try? JSONDecoder().decode(ClipboardStore.Saved.self, from: Data(contentsOf: folder.appending(path: "history.json")))
    }

    @discardableResult private static func write(_ saved: ClipboardStore.Saved, to folder: URL) -> Bool {
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        return (try? JSONEncoder().encode(saved).write(to: folder.appending(path: "history.json"), options: .atomic)) != nil
    }

    /// The image as the app copied it, without decoding it.
    private static func imageData(_ pasteboard: UIPasteboard) -> (data: Data, type: UTType)? {
        for type in [UTType.png, .jpeg, .heic, .gif, .webP] {
            if let data = pasteboard.data(forPasteboardType: type.identifier) { return (data, type) }
        }
        return pasteboard.image?.pngData().map { ($0, .png) }
    }
}
