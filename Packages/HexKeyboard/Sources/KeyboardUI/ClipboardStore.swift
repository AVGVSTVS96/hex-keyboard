import CryptoKit
import Foundation
import ImageIO
import KeyboardCore
import UIKit
import UniformTypeIdentifiers

/// Keeps what you copy (docs/design.md, "Clipboard"), in the App Group so the app shows the history the keyboard keeps,
/// never online. Nothing runs in the background: the keyboard looks at the clipboard when it appears and when the
/// clipboard panel opens, and the app when it comes to the front, and each keeps whatever changed since either last
/// looked. Reading the clipboard needs Full Access, and Paste from Other Apps (`refused`).
public final class ClipboardStore {
    private struct Saved: Codable {
        var history = ClipboardHistory()
        var seen = 0
    }

    private var saved: Saved
    private let folder: URL
    /// The keyboard's own copy of everything, since iOS deletes the group's container whenever an install leaves no app
    /// claiming the group. A group without a history takes this one, which is also how the history the keyboard kept
    /// before the group held it got there.
    private let backup: URL?

    /// Password managers mark what they copy with these, so it's never kept.
    static let concealed = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    public static let shared = FileManager.default.containerURL(forSecurityApplicationGroupIdentifier: SettingsStore.appGroup)?.appending(path: "Library/clipboard")
    static let own = URL.applicationSupportDirectory.appending(path: "clipboard")

    public init(folder: URL? = ClipboardStore.shared, backup: URL? = nil) {
        self.folder = folder ?? Self.own
        self.backup = backup == self.folder ? nil : backup
        saved = Saved()
        reload()
    }

    public var history: ClipboardHistory { saved.history }

    /// Whether the history is in the folder yet. The keyboard starts it, from its own copy when it has one, so the app
    /// keeps nothing before then: what it kept would stand in for everything the keyboard had.
    public var started: Bool { FileManager.default.fileExists(atPath: folder.appending(path: "history.json").path()) }

    /// Whether iOS refused the keyboard's last look at the clipboard. iOS counts a keyboard's reads as its app's, even
    /// inside another app, and without asking refuses them unless Settings › Apps › Hex › Paste from Other Apps is Allow.
    public private(set) var refused = false

    /// Keeps what's on the clipboard if it changed since the keyboard last looked.
    public func catchUp(_ pasteboard: UIPasteboard = .general, now: Date = .now) {
        reload()
        guard pasteboard.changeCount != saved.seen else { return }
        defer { save() }
        guard !pasteboard.types.contains(where: Self.concealed.contains) else { return saved.seen = pasteboard.changeCount }
        let content: ClipboardHistory.Item.Content?
        if pasteboard.hasStrings {
            content = pasteboard.string.map(ClipboardHistory.Item.Content.text)
        } else if pasteboard.hasImages {
            content = Self.imageData(pasteboard).map(saveImage)
        } else {
            return saved.seen = pasteboard.changeCount
        }
        refused = content == nil
        if SettingsStore.pasteAllowed != !refused { SettingsStore.pasteAllowed = !refused }
        guard let content else { return }
        saved.seen = pasteboard.changeCount
        if case .text(let text) = content, text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return }
        saved.history.keep(content, at: now.timeIntervalSince1970)
    }

    /// Something the keyboard put on the clipboard itself, which it doesn't keep.
    public func skip(changeCount: Int) {
        reload()
        saved.seen = changeCount
        save()
    }

    public func setPinned(_ pinned: Bool, _ content: ClipboardHistory.Item.Content) {
        reload()
        saved.history.setPinned(pinned, content)
        save()
    }

    public func remove(_ content: ClipboardHistory.Item.Content) {
        reload()
        saved.history.remove(content)
        deleteFiles([content])
        save()
    }

    /// Deletes everything but what's pinned.
    public func removeUnpinned() {
        reload()
        deleteFiles(saved.history.removeUnpinned())
        save()
    }

    /// Puts an image item back on the clipboard, for you to paste.
    public func copy(image name: String, to pasteboard: UIPasteboard = .general) {
        guard let data = try? Data(contentsOf: folder.appending(path: name)), let type = UTType(filenameExtension: (name as NSString).pathExtension) else { return }
        pasteboard.setData(data, forPasteboardType: type.identifier)
        skip(changeCount: pasteboard.changeCount)
    }

    /// A small image for an image item's row, decoded at the size it shows, so a big screenshot never fills the
    /// keyboard's memory.
    public func thumbnail(_ name: String, side: CGFloat) -> UIImage? {
        guard let source = CGImageSourceCreateWithURL(folder.appending(path: name) as CFURL, nil),
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: side, kCGImageSourceCreateThumbnailWithTransform: true] as CFDictionary)
        else { return nil }
        return UIImage(cgImage: image)
    }

    private func saveImage(_ image: (data: Data, type: UTType)) -> ClipboardHistory.Item.Content {
        let name = SHA256.hash(data: image.data).map { String(format: "%02x", $0) }.joined() + "." + (image.type.preferredFilenameExtension ?? "img")
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try? image.data.write(to: folder.appending(path: name), options: .atomic)
        return .image(name)
    }

    private func deleteFiles(_ contents: [ClipboardHistory.Item.Content]) {
        for case .image(let name) in contents { try? FileManager.default.removeItem(at: folder.appending(path: name)) }
    }

    /// The history as the file holds it now. iOS can run the keyboard in more than one app at once, and the app beside
    /// it, each with the history it read when it opened, so each takes the file's before changing it, and one never
    /// writes over what another kept.
    public func reload() {
        if let saved = Self.read(folder) ?? restore() { self.saved = saved }
    }

    private func restore() -> Saved? {
        guard let backup, let saved = Self.read(backup) else { return nil }
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        for name in (try? FileManager.default.contentsOfDirectory(atPath: backup.path())) ?? [] {
            try? FileManager.default.copyItem(at: backup.appending(path: name), to: folder.appending(path: name))
        }
        return saved
    }

    private static func read(_ folder: URL) -> Saved? {
        try? JSONDecoder().decode(Saved.self, from: Data(contentsOf: folder.appending(path: "history.json")))
    }

    private func save() {
        write(to: folder)
        guard let backup else { return }
        write(to: backup)
        let images = Set(saved.history.items.compactMap { if case .image(let name) = $0.content { name } else { nil } })
        let backedUp = Set((try? FileManager.default.contentsOfDirectory(atPath: backup.path())) ?? []).subtracting(["history.json"])
        for name in images.subtracting(backedUp) { try? FileManager.default.copyItem(at: folder.appending(path: name), to: backup.appending(path: name)) }
        for name in backedUp.subtracting(images) { try? FileManager.default.removeItem(at: backup.appending(path: name)) }
    }

    private func write(to folder: URL) {
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try? JSONEncoder().encode(saved).write(to: folder.appending(path: "history.json"), options: .atomic)
    }

    /// The image as the app copied it, without decoding it.
    private static func imageData(_ pasteboard: UIPasteboard) -> (data: Data, type: UTType)? {
        for type in [UTType.png, .jpeg, .heic, .gif, .webP] {
            if let data = pasteboard.data(forPasteboardType: type.identifier) { return (data, type) }
        }
        return pasteboard.image?.pngData().map { ($0, .png) }
    }
}
